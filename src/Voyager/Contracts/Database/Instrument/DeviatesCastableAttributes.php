<?php

namespace Voyager\Contracts\Database\Instrument;

interface DeviatesCastableAttributes
{
    /**
     * Increment the attribute.
     *
     * @param  \Voyager\Database\Instrument\Model  $model
     * @param  string  $key
     * @param  mixed  $value
     * @param  array  $attributes
     * @return mixed
     */
    public function increment($model, string $key, $value, array $attributes);

    /**
     * Decrement the attribute.
     *
     * @param  \Voyager\Database\Instrument\Model  $model
     * @param  string  $key
     * @param  mixed  $value
     * @param  array  $attributes
     * @return mixed
     */
    public function decrement($model, string $key, $value, array $attributes);
}
